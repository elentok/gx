// designMessage is the assistant message for the turn-th prompt (from zero).
// Without a script a /gx-design prompt gets the next round and any other text
// the run-end message; a script that has run out falls back to the same.
func (t *tui) designMessage(text string, script []string) string {
	return t.design.Message(text, script)
}

// designTurn plays one turn, picking its message with designMessage. The
// message lands in the transcript while the turn is busy, and the turn ends
// shortly after so the server sees the busy-to-idle change that raises the
// Actionable.
func (t *tui) designTurn(text string) error {
	t.prompt = text
	script := t.design.TurnScript(t.pid.Cwd, text)
	if IsDesignPrompt(text) {
		t.design.Active = true
	}
	busy := DesignTurnTime
	if t.design.Turns < len(script) && script[t.design.Turns] == DesignTurnSlow {
		busy = DesignSlowTime
	}
	cfg, _ := LoadWorkerConfig(t.pid.Cwd)
	held := cfg.DesignHold && t.design.Turns == 0
	msg := t.designMessage(text, script)
	// Busy comes first: a message that appears while the session still reads
	// idle lets a test prompt it before the turn has started, and that prompt is lost.
	if err := t.setStatus(StatusBusy, ""); err != nil {
		return err
	}
	path, err := t.transcriptPath()
	if err != nil {
		return err
	}
	// An answer is a person message in the transcript, as in claude: it ends
	// the round the answer is for.
	if !IsDesignPrompt(text) {
		if err := AppendMessage(path, "user", text); err != nil {
			return err
		}
	}
	reply := func() error {
		return AppendReply(path, t.opts.model, []map[string]any{{"type": "text", "text": msg}})
	}
	if held {
		// The turn is busy already, so the launch prompt counts as delivered; the
		// reply and the end of the turn wait for the test to release the hold.
		go func() {
			WaitHold(cfg)
			if reply() == nil {
				time.Sleep(busy)
				_ = SendControl(t.ctlPath, Control{Action: ActionFinish})
			}
		}()
		return nil
	}
	if err := reply(); err != nil {
		return err
	}
	go func() {
		time.Sleep(busy)
		_ = SendControl(t.ctlPath, Control{Action: ActionFinish})
	}()
	return nil
}

const chatReply = "Sure, here is a short answer."

// chatTurn plays a plain prompt as a chat turn: the person message and a
// scripted reply land in the transcript, and the turn ends shortly after.
func (t *tui) chatTurn(text string, images []string) error {
	t.prompt = text
	if err := t.setStatus(StatusBusy, ""); err != nil {
		return err
	}
	path, err := t.transcriptPath()
	if err != nil {
		return err
	}
	if len(images) > 0 {
		err = writeImagePrompt(path, text, images)
	} else {
		err = AppendMessage(path, "user", text)
	}
	if err != nil {
		return err
	}
	if strings.Contains(text, ChatSlowMarker) {
		return nil
	}
	if err := AppendReply(path, t.opts.model, []map[string]any{{"type": "text", "text": chatReply}}); err != nil {
		return err
	}
	go func() {
		time.Sleep(DesignTurnTime)
		_ = SendControl(t.ctlPath, Control{Action: ActionFinish})
	}()
	return nil
}

// apiError appends the assistant line claude writes when an API call fails.
func (t *tui) apiError(c Control) error {
	path, err := t.transcriptPath()
	if err != nil {
		return err
	}
	return AppendEntry(path, "assistant", []map[string]any{{"type": "text", "text": c.Message}}, map[string]any{
		"isApiErrorMessage": true,
		"error":             c.Error,
		"apiErrorStatus":    c.Status,
	})
}

// writeCommandOutput appends the three lines claude writes for a built-in
// command: the caveat, the command itself and its stdout.
func (t *tui) writeCommandOutput(command, stdout string) error {
	path, err := t.transcriptPath()
	if err != nil {
		return err
	}
	name := strings.TrimPrefix(command, "/")
	lines := []struct {
		content string
		extra   map[string]any
	}{
		{"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>", map[string]any{"isMeta": true}},
		{"<command-name>" + command + "</command-name>\n<command-message>" + name + "</command-message>\n<command-args></command-args>", nil},
		{"<local-command-stdout>" + stdout + "</local-command-stdout>", nil},
	}
	for _, l := range lines {
		if err := AppendEntry(path, "user", l.content, l.extra); err != nil {
			return err
		}
	}
	return nil
}

// rateLimit answers the worker's prompt with the rate-limit error claude writes
// when the usage limit is hit. The turn goes busy first, as in claude: a launch
// prompt only counts as delivered once the server sees a turn start, and
// without it the launch is retried and the hold never applies.
func (t *tui) rateLimit(cfg WorkerConfig) error {
	reset := DefaultRateLimitReset
	if d, err := time.ParseDuration(cfg.RateLimitReset); err == nil && d > 0 {
		reset = d
	}
	msg := "You've hit your limit · resets " + time.Now().Add(reset).Format("3:04pm")
	if cfg.RateLimitFromUsage {
		msg = "You've hit your limit"
	}
	if err := t.setStatus(StatusBusy, ""); err != nil {
		return err
	}
	if cfg.RateLimitFromUsage {
		// The server reads the usage record when it sees the limit, so it must exist by then.
		t.limitResetsAt = time.Now().Add(reset).Unix()
		t.runStatusLine()
	}
	if err := t.apiError(Control{Error: "rate_limit", Status: 429, Message: msg}); err != nil {
		return err
	}
	go func() {
		time.Sleep(DesignTurnTime)
		_ = SendControl(t.ctlPath, Control{Action: ActionFinish})
	}()
	return nil
}

func (t *tui) transcriptPath() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return TUITranscriptPath(home, t.pid.Cwd, t.pid.SessionID), nil
}
